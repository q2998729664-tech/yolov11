class RFAConv(nn.Module):
    """完整版RFAConv：实现每个感受野拥有独特的卷积内核.

    论文原理：
    1. 通过分组卷积提取每个感受野的特征 (generate_feature)
    2. 通过全局平均池化和1x1分组卷积生成注意力权重 (get_weight)
    3. 将注意力权重应用于感受野特征 (weighted * feature)
    4. 重组特征图并通过最终卷积输出

    Args:
        in_channel: 输入通道数
        out_channel: 输出通道数
        kernel_size: 卷积核大小（默认3）
        stride: 步长（默认1）
    """

    def __init__(self, in_channel, out_channel, kernel_size=3, stride=1):
        super().__init__()
        self.kernel_size = kernel_size
        self.stride = stride

        # 1️⃣ 注意力权重生成模块：决定每个感受野内各位置的重要性
        # 先池化聚合局部信息，再用1x1分组卷积生成注意力权重
        self.get_weight = nn.Sequential(
            nn.AvgPool2d(kernel_size=kernel_size, padding=kernel_size // 2, stride=stride),
            nn.Conv2d(in_channel, in_channel * (kernel_size**2), kernel_size=1, groups=in_channel, bias=False),
        )

        # 2️⃣ 感受野特征生成模块：提取每个感受野的原始特征
        # 使用分组卷积高效实现，相当于可学习的unfold操作
        self.generate_feature = nn.Sequential(
            nn.Conv2d(
                in_channel,
                in_channel * (kernel_size**2),
                kernel_size=kernel_size,
                padding=kernel_size // 2,
                stride=stride,
                groups=in_channel,
                bias=False,
            ),
            nn.BatchNorm2d(in_channel * (kernel_size**2)),
            nn.ReLU(inplace=True),
        )

        # 3️⃣ 最终卷积模块：将加权的感受野特征压缩回输出空间
        # 注意：此处stride=kernel_size是为了将展开的特征重新聚合
        self.conv = nn.Sequential(
            nn.Conv2d(in_channel, out_channel, kernel_size=kernel_size, stride=kernel_size),
            nn.BatchNorm2d(out_channel),
            nn.ReLU(inplace=True),
        )

    def forward(self, x):
        b, c = x.shape[0], x.shape[1]

        # 生成注意力权重 (batch, c * k^2, h, w)
        weight = self.get_weight(x)
        h, w = weight.shape[2:]

        # 重塑并应用Softmax，确保每个感受野内注意力权重和为1
        # 形状: (b, c, k^2, h, w)
        weight = weight.view(b, c, self.kernel_size**2, h, w)
        weight = weight.softmax(dim=2)  # 在k^2维度上归一化

        # 生成感受野特征，并重塑为相同形状
        feature = self.generate_feature(x)
        feature = feature.view(b, c, self.kernel_size**2, h, w)

        # 将注意力权重应用于特征 (逐元素相乘)
        weighted_feature = feature * weight  # 形状不变

        # 重组特征图：将k^2维度的特征展开到空间维度
        # 从 (b, c, k^2, h, w) -> (b, c, h*k, w*k)
        out = rearrange(
            weighted_feature, "b c (k1 k2) h w -> b c (h k1) (w k2)", k1=self.kernel_size, k2=self.kernel_size
        )

        # 最终卷积：将展开的特征压缩回输出通道数
        out = self.conv(out)
        return out
